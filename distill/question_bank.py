DIFFICULTY = {1: "easy", 2: "medium", 3: "hard"}


def normalize(text):
    return " ".join(text.split())


def make_id(prompt):
    return "q_" + hashlib.sha1(normalize(prompt).encode("utf-8")).hexdigest()[:12]


def _question(domain, kind, difficulty, prompt, lang="ru"):
    prompt = normalize(prompt)
    return {
        "id": make_id(prompt),
        "lang": lang,
        "domain": domain,
        "kind": kind,
        "difficulty": DIFFICULTY[difficulty],
        "prompt": prompt,
    }


def _generic(domain, spec, rng):
    topics = spec["topics"]
    pair_map = {a: b for a, b in COMPARE_PAIRS.get(domain, [])}
    skip = SKIP_UNIVERSAL.get(domain, set())
    universal = [k for k in UNIVERSAL_ARCH if k not in skip]
    out = []
    for topic in topics:
        for key in spec["arch"] + universal:
            info = ARCH[key]
            if key == "compare":
                if topic in pair_map:
                    tpl = info["templates"][rng.randrange(len(info["templates"]))]
                    prompt = tpl.format(topic=topic, topic2=pair_map[topic])
                else:
                    tpl = COMPARE_FALLBACK[rng.randrange(len(COMPARE_FALLBACK))]
                    prompt = tpl.format(topic=topic)
            else:
                tpl = info["templates"][rng.randrange(len(info["templates"]))]
                prompt = tpl.format(topic=topic)
            out.append(_question(domain, info["kind"], info["difficulty"], prompt))
    return out


def _finite(rng, low, high, step=1):
    if step == 1:
        return rng.randint(low, high)
    return rng.randrange(low, high + 1, step)


def _format_num(x):
    if isinstance(x, float):
        if abs(x - round(x)) < 1e-9:
            return str(int(round(x)))
        return ("%.4f" % x).rstrip("0").rstrip(".")
    return str(x)


