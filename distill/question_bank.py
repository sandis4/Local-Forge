def build_master():
    rng = random.Random(20261108)
    lists = {}
    for name, spec in DOMAINS.items():
        lists[name] = _generic(name, spec, rng)
    lists["math"].extend(_numeric_math(rng))
    lists["science"].extend(_numeric_science(rng))
    lists["programming"].extend(_extra_programming(rng))
    lists["russian"].extend(_extra_russian(rng))
    lists["tech"].extend(_extra_tech(rng))
    lists["everyday"].extend(_extra_everyday(rng))
    lists["humanities"].extend(_extra_humanities(rng))
    lists["writing"].extend(_extra_writing(rng))
    lists["professional"].extend(_extra_professional(rng))
    lists["logic"].extend(_extra_logic(rng))
    lists["english"].extend(_extra_english(rng))
    lists["creative"].extend(_extra_creative(rng))

    order = list(DOMAINS.keys())
    seen = set()
    unique = {name: [] for name in order}
    for name in order:
        for q in lists[name]:
            if q["id"] in seen:
                continue
            seen.add(q["id"])
            unique[name].append(q)
        random.Random("order:" + name).shuffle(unique[name])

    master = []
    idx = 0
    while True:
        added = False
        for name in order:
            if idx < len(unique[name]):
                master.append(unique[name][idx])
                added = True
        if not added:
            break
        idx += 1
    return master, unique
