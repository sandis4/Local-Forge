/// Динамические сообщения: crate::tf!("шагов {}", "steps {}", n)
#[macro_export]
macro_rules! tf {
    ($ru:literal, $en:literal $(, $arg:expr)* $(,)?) => {
        if crate::i18n::lang() == "en" {
            format!($en $(, $arg)*)
        } else {
            format!($ru $(, $arg)*)
        }
    };
}
