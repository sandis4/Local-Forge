//! Минимальная локализация RU/EN: язык — глобальный AtomicU8,
//! tr() оставляет русский текст как есть и подменяет его английским
//! переводом, если выбран EN. Динамические строки — через crate::tf!.

use std::sync::atomic::{AtomicU8, Ordering};

static LANG: AtomicU8 = AtomicU8::new(0); // 0 = ru, 1 = en

pub fn set_lang(lang: &str) {
    let code = if lang.eq_ignore_ascii_case("en") { 1 } else { 0 };
    LANG.store(code, Ordering::Relaxed);
}

pub fn lang() -> &'static str {
    if LANG.load(Ordering::Relaxed) == 1 { "en" } else { "ru" }
}

pub fn tr(text: &'static str) -> &'static str {
    if LANG.load(Ordering::Relaxed) == 1 {
        en(text)
    } else {
        text
    }
}

